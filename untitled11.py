# --- STEP 2: Define Backend Python Functions ---

def save_audio(base64data):
    header, encoded = base64data.split(',', 1)
    binary_data = base64.b64decode(encoded)

    # Ensure directory exists
    os.makedirs('/content/sample_data', exist_ok=True)
    file_path = '/content/sample_data/recorded_audio.wav'

    with open(file_path, 'wb') as f:
        f.write(binary_data)

def run_nlp_pipeline():
    print("\n--------------------------------------------------")
    print("🚀 Starting Speech-to-Text & NLP Pipeline...")

    # Load the spaCy NLP model
    nlp = spacy.load("en_core_web_sm")

    original_audio_path = "/content/sample_data/recorded_audio.wav"
    converted_audio_path = "/content/sample_data/recorded_audio_converted.wav"

    try:
        if not os.path.exists(original_audio_path):
            raise FileNotFoundError(f"File not found at {original_audio_path}")

        print("🔄 Converting browser recording to standard PCM WAV...")
        subprocess.run([
            'ffmpeg', '-y', '-i', original_audio_path,
            '-acodec', 'pcm_s16le', '-ar', '16000', '-ac', '1',
            converted_audio_path
        ], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

        recognizer = sr.Recognizer()
        with sr.AudioFile(converted_audio_path) as source:
            print("📁 Loading your converted voice...")
            audio_data = recognizer.record(source)

            print("🔄 Converting speech to text via Google Speech API...")
            text = recognizer.recognize_google(audio_data)
            print(f"\n✨ [Transcribed Text]: {text}")

            # --- Pass Transcribed Text to spaCy NLP Pipeline ---
            doc = nlp(text)

            print("\n--- NLP Analysis Results ---")
            print("Tokens and Parts of Speech:")
            for token in doc:
                print(f"  {token.text} -> {token.pos_}")

            if doc.ents:
                print("\nNamed Entities Found:")
                for ent in doc.ents:
                    print(f"  {ent.text} -> {ent.label_}")
            else:
                print("\nNamed Entities Found: None")

    except FileNotFoundError:
        print(f"❌ Error: The audio file was not found. Please record first.")
    except sr.UnknownValueError:
        print("❌ Speech Recognition could not understand the audio. Try speaking louder or clearer.")
    except sr.RequestError as e:
        print(f"❌ Could not connect to Google Speech Recognition service; {e}")
    except Exception as e:
        print(f"❌ An unexpected error occurred: {e}")

# Register callbacks so JavaScript can call Python functions seamlessly
output.register_callback('notebook.save_audio', save_audio)
output.register_callback('notebook.run_nlp', run_nlp_pipeline)